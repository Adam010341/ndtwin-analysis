def die(who, msg):
    raise SystemExit(f"{who}: {msg}")


def sha16(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()[:16]


def new_canvas(w, h):
    fig = plt.figure(figsize=(w, h))
    ax = fig.add_axes([0, 0, 1, 1])
    ax.set_xlim(0, w)
    ax.set_ylim(h, 0)
    ax.axis("off")
    return fig, ax


def title(ax, text, w):
    assert len(text) <= 45, f"canvas title longer than 45 chars: {text!r}"
    ax.text(0.45, 0.48, text, fontsize=22, fontweight="bold", color=INK, va="center")


#: Adam 2026-10-12: a figure carries only what a reader will read. Provenance (commit shas, dates, run ids, source
#: lines, generator or file names, versions) lives in the speaker notes, the template and the companion .md, never
#: on the canvas. save_all refuses to write a figure with any text that looks like provenance.
PROVENANCE = [
    ("a commit sha or hash", re.compile(r"\b(?=[0-9a-f]*[0-9])(?=[0-9a-f]*[a-f])[0-9a-f]{7,64}\b")),
    ("a date", re.compile(r"\b20\d\d-[01]\d-[0-3]\d\b|\b\d{1,2}/\d{1,2}/20\d\d\b")),
    ("a time stamp", re.compile(r"\b\d\d:\d\d(:\d\d)?Z\b|\bT\d{6}Z\b")),
    ("a file or generator name", re.compile(r"\b[\w-]+\.(py|js|sh|tsv|json|md|log|txt|cpp|hpp|p4)\b")),
    ("a provenance word", re.compile(r"(?i)\b(commit|sha256|generated by|regenerate|produced by|source:|"
                                     r"sources:|run id|matplotlib|data:|read at|as of)\b")),
    ("a path:line citation", re.compile(r"[\w/.-]+:\d+(-\d+)?\b(?<!:8000)(?<!:8080)(?<!:8081)")),
]


def provenance_on_canvas(fig):
    """[(text, why)] for every text artist on the figure that reads like a provenance footer."""
    from matplotlib.text import Text
    bad = []
    for t in fig.findobj(Text):
        s = t.get_text()
        if not s or not t.get_visible():
            continue
        for why, rx in PROVENANCE:
            if rx.search(s):
                bad.append((s, why))
                break
    return bad


def save_all(fig, outdir, stem):
    bad = provenance_on_canvas(fig)
    if bad:
        die(stem, "provenance text on the canvas (it belongs in the notes, not on the figure): "
                  + "; ".join(f"{s!r} looks like {why}" for s, why in bad[:4]))
    hires = os.path.join(outdir, "_hires")
    os.makedirs(hires, exist_ok=True)
    for ext in ("pdf", "png", "svg"):
        kw = {"dpi": 300} if ext == "png" else {}
        fig.savefig(os.path.join(outdir, f"{stem}.{ext}"), facecolor=WHITE, **kw)
    fig.savefig(os.path.join(hires, f"{stem}.png"), facecolor=WHITE, dpi=500)
    plt.close(fig)


def write_companion(outdir, stem, script_path, text):
    """Write <stem>.md from the generator (the file tool may refuse .md; the generator does not)."""
    when = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    cmd = ("cd generator   # from the deck folder\n"
           f'"${{NDTWIN_PLOTVENV:-../../NDTwin Slide material 820/.plotvenv/bin/python3}}" {os.path.basename(script_path)}')
    body = (text.rstrip() + "\n\n## Regenerate\n\n```bash\n" + cmd + "\n```\n\n"
            f"Last produced: {when} (UTC); matplotlib {matplotlib.__version__}; generator "
            f"`{os.path.basename(script_path)}` sha256 `{sha16(script_path)}...`, shared style "
            f"`figstyle_1028.py` sha256 `{sha16(os.path.join(os.path.dirname(script_path), 'figstyle_1028.py'))}...`.\n"
            "\n[Co-developed with claude code -- Adam]\n")
    # no absolute path in a companion: the kernel repo is K, this deck folder is "."
    body = body.replace(KERNEL, "K").replace(DECK + os.sep, "").replace(DECK, ".")
    if re.search(r"/home/|local-agent-mode-sessions", body):
        die(stem, "companion .md still carries an absolute home path")
    with open(os.path.join(outdir, stem + ".md"), "w", encoding="utf-8") as f:
        f.write(body)


# ------------------------------------------------------------------ figure specs (figures_spec/*.txt)
#: A spec is plain text: a "Title on canvas (= slide title): ..." line, then sections whose header is an
#: upper-case word at column 0 ("LANES", "STEPS", "ARROWS", ...). A row is a line indented two spaces with
#: fields split on " | "; the lines indented four or more spaces under a row are its evidence.
#: [Co-developed with claude code -- Adam]
def read_spec(who, path, title_drawn):
    if not os.path.exists(path):
        die(who, f"spec file missing: {path}")
    text = open(path, encoding="utf-8").read()
    m = re.search(r"^Title on canvas[^:]*:\s*(.+)$", text, re.M)
    if not m or m.group(1).strip() != title_drawn:
        die(who, f"{os.path.basename(path)} canvas title is {m.group(1).strip() if m else None!r}, "
                 f"the figure draws {title_drawn!r}")
    if len(title_drawn) > 45:
        die(who, f"canvas title longer than 45 chars: {title_drawn!r}")
    sections, cur, last = {}, None, None
    for ln in text.splitlines():
        h = re.match(r"^([A-Z][A-Z ]+?)(\s*\(.*)?$", ln)
        if h and not ln.startswith(" "):
            cur = h.group(1).strip()
            sections[cur] = []
            last = None
            continue
        if cur is None:
            continue
        r = re.match(r"^ {2}(\S.*)$", ln)
        if r:
            last = {"fields": [f.strip() for f in r.group(1).split(" | ")], "evidence": []}
            sections[cur].append(last)
            continue
        e = re.match(r"^ {4,}(\S.*)$", ln)
        if e and last is not None:
            last["evidence"].append(e.group(1).strip())
            continue
        if ln.strip() == "":
            continue
        last = None
    return text, sections


def need_section(who, sections, name, path):
    if name not in sections or not sections[name]:
        die(who, f"{os.path.basename(path)} has no {name} section (or it is empty)")
    return sections[name]


def text_fits(who, fig, ax, artist, x0, x1, pad=0.06):
    """Stop if a drawn text's rendered extent (in data inches) leaves [x0 + pad, x1 - pad] horizontally.
    The canvas is 1 data unit = 1 inch (new_canvas), so the check reads the extent the PNG will have."""
    r = fig.canvas.get_renderer()
    bb = artist.get_window_extent(renderer=r).transformed(ax.transData.inverted())
    lo, hi = min(bb.x0, bb.x1), max(bb.x0, bb.x1)
    if lo < x0 + pad - 1e-6 or hi > x1 - pad + 1e-6:
        die(who, f"text {artist.get_text()!r} spans x {lo:.2f}-{hi:.2f} in, its box allows "
                 f"{x0 + pad:.2f}-{x1 - pad:.2f} in (it would stick out of its box)")
    return hi - lo
